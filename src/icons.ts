export type IconName = keyof typeof PATHS;

const NS = 'http://www.w3.org/2000/svg';

export function icon(name: IconName, size = 16, cls = ''): SVGSVGElement {
  const svg = document.createElementNS(NS, 'svg');
  for (const [k, v] of Object.entries({
    viewBox: '0 0 24 24', width: String(size), height: String(size), fill: 'none', stroke: 'currentColor',
    'stroke-width': '2', 'stroke-linecap': 'round', 'stroke-linejoin': 'round', 'aria-hidden': 'true', focusable: 'false',
  })) svg.setAttribute(k, v);
  svg.setAttribute('class', `ic ic-${name}${cls ? ' ' + cls : ''}`);
  svg.innerHTML = PATHS[name];
  return svg;
}

/** Static markup: <span data-icon="rotate-cw" data-size="14"></span> becomes the icon. */
export function hydrateIcons(root: ParentNode = document) {
  for (const slot of root.querySelectorAll<HTMLElement>('[data-icon]')) {
    const name = slot.dataset.icon as IconName;
    if (!(name in PATHS)) continue;
    slot.replaceWith(icon(name, Number(slot.dataset.size) || 16, slot.dataset.class ?? ''));
  }
}
